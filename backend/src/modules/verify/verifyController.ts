import { Request, Response, NextFunction } from "express"
import { prisma } from "../../utils/prisma.js"

export async function verifyReport(req: Request, res: Response, next: NextFunction) {
  try {
    const { reportId } = req.params
    if (!reportId || !String(reportId).startsWith("EG-")) {
      return res.status(400).json({ success: false, error: { message: "Invalid report ID format" } })
    }
    const report = await prisma.report.findUnique({ where: { reportId: String(reportId) } })
    if (!report) {
      return res.status(404).json({ success: false, error: { message: "Report not found", reportId } })
    }
    // Fetch safe info
    let exam: any = null
    let student: any = null
    let generatedAt = report.generatedAt
    if (report.sessionId) {
      const session = await prisma.examSession.findUnique({ where: { id: report.sessionId }, include: { exam: true, student: { select: { name: true, email: true } } } })
      if (session) {
        exam = session.exam ? { id: session.exam.id, title: session.exam.title, subject: session.exam.subject } : null
        student = session.student ? { name: session.student.name } : null // policy: only name, not full email? We show name only for privacy
        // Use session submittedAt if needed
      }
    } else if (report.examId) {
      const e = await prisma.exam.findUnique({ where: { id: report.examId } })
      if (e) exam = { id: e.id, title: e.title, subject: e.subject }
    }
    // If directly linked to review
    if (!exam && report.reviewId) {
      const rev = await prisma.integrityReview.findUnique({ where: { id: report.reviewId }, include: { session: { include: { exam: true, student: { select: { name: true } } } } } })
      if (rev?.session?.exam) exam = { id: rev.session.exam.id, title: rev.session.exam.title, subject: rev.session.exam.subject }
      if (rev?.session?.student) student = { name: rev.session.student.name }
    }
    let version = "1.0"
    try {
      const meta = report.metadata ? JSON.parse(report.metadata) : {}
      version = meta.version || version
    } catch {}

    // Return safe verification payload
    res.json({
      success: true,
      data: {
        reportId: report.reportId,
        exists: true,
        status: "VALID",
        reportType: report.reportType,
        exam: exam ? { title: exam.title, subject: exam.subject } : null,
        student: student ? { name: student.name } : null, // per policy, limited
        generatedAt,
        version,
        message: "This report was generated by ExamGuard and is authentic.",
      },
    })
  } catch (e) {
    next(e)
  }
}

